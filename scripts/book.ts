/**
 * Builds the arena's opening book for one board: random openings kept only
 * when they are level (src/ai/openings.ts).
 *
 *   npx vite-node scripts/book.ts -- --board=48 --count=300 --plies=4
 *
 * Writes src/ai/positions/book<board>.ts. Openings are stored as MOVES from the
 * initial position (moveKey), not as a ZIP: a ZIP is re-anchored onto a board
 * template when read back, and after edge rings come off that is not always the
 * template it came from. The ZIP is kept alongside for people to read.
 */

import { writeFileSync } from 'node:fs';
import { stateToZip } from '../src/game/zip';
import { isLevelOpening, randomOpening } from '../src/ai/openings';

const args = new Map<string, string>();
for (const raw of process.argv.slice(2)) {
  const m = /^--([^=]+)=(.*)$/.exec(raw);
  if (m) args.set(m[1], m[2]);
}
const board = Number(args.get('board') ?? 48) as 37 | 48 | 61;
const count = Number(args.get('count') ?? 300);
const plies = Number(args.get('plies') ?? 4);

const book: Array<{ seed: number; moves: string[]; zip: string }> = [];
let tried = 0;
for (let seed = 1; book.length < count; seed++) {
  tried++;
  const { state, moves } = randomOpening(seed, board, plies);
  if (isLevelOpening(state)) book.push({ seed, moves, zip: stateToZip(state) });
}

const lines = book.map(o => `  { moves: ${JSON.stringify(o.moves)}, zip: '${o.zip}' }, // seed ${o.seed}`);
const file = `src/ai/positions/book${board}.ts`;
writeFileSync(
  file,
  `/**
 * The arena's opening book for the ${board}-ring board: ${book.length} random ${plies}-ply openings in
 * which nobody has captured anything and nothing can be captured (${book.length} of ${tried} tried).
 * Generated by scripts/book.ts — regenerate rather than edit.
 */

import type { BookOpening } from './books';

export const BOOK_${board}: BookOpening[] = [
${lines.join('\n')}
];
`,
);
console.log(`wrote ${book.length} openings (${tried} tried, ${((100 * book.length) / tried).toFixed(0)}% level) to ${file}`);
